import assert from 'node:assert/strict';
import {classifyBlocks,makePlan,validateOfficialAttrs} from '../genoffice-official-typeset/scripts/official-typeset-core.mjs';
const p=(text,index,type='paragraph')=>({text,index,type});
const blocks=[p('关于开展工作的通知',0),p('各单位：',1),p('一、工作目标',2),p('（一）核实情况',3),p('1. 保存资料',4),p('一、请认真核实有关数据，形成资料清单后统一报送。',5),p('附件：清单',6),p('某某公司',7),p('2026年10月22日',8),p('',9),p('1. 已有自动编号',10,'listitem'),p('表格数据',11,'table')];
const roles=classifyBlocks(blocks).map(b=>b.role);
assert.deepEqual(roles,['title','addressee','heading1','heading2','heading3','body','attachment','signature','date','blank','body','skip']);
const original=structuredClone(blocks),plan=makePlan(blocks);
assert.deepEqual(blocks,original);
assert.deepEqual(plan.entries.map(b=>b.text),blocks.map(b=>b.text));
assert.equal(plan.ops.filter(o=>o.op==='setOfficialParagraphFormat').length,11);
assert(plan.ops.filter(o=>o.op==='setOfficialParagraphFormat').every(o=>o.attrs.lineRule==='exact'&&o.attrs.lineRawTwips===560));
assert(!plan.ops.some(o=>o.target?.blockIndexes.includes(11)));
assert(!plan.ops.some(o=>o.op==='applyStyle'&&o.target.blockIndexes.includes(10)));
const list=plan.ops.find(o=>o.op==='setOfficialParagraphFormat'&&o.target.blockIndexes.includes(10));
assert(!Object.hasOwn(list.attrs,'indentFirstLine'));
assert(plan.ops.filter(o=>o.op==='define_style').every(o=>o.run.bold===false&&o.basedOn===null));
assert.equal(classifyBlocks(blocks,{5:'heading1'})[5].role,'heading1');
assert.throws(()=>makePlan(blocks,{overrides:{77:'body'}}));
assert.throws(()=>makePlan(blocks,{overrides:{11:'body'}}));
assert(validateOfficialAttrs({lineRawTwips:NaN}));
assert(validateOfficialAttrs({docxIndex:0}));
assert.throws(()=>makePlan(blocks,{profile:{lineHeightPt:12}}));
assert.equal(makePlan(blocks,{profile:{lineHeightPt:30}}).ops.find(o=>o.op==='setOfficialParagraphFormat').attrs.lineRawTwips,600);
console.log('Regression checks passed: role inference, source preservation, exact spacing, isolated styles, list/table preservation, rejected invalid input.');
